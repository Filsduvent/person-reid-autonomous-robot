def canonical(path):
    path = Path(path).absolute()
    if '..' in path.parts or path.resolve() != path:
        raise ValueError('Path alias or traversal prohibited')
    return path


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def encode(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False, allow_nan=False).encode('utf-8')


def digest(value):
    return hashlib.sha256(encode(value)).hexdigest()


def git(root, *args, binary=False):
    value = subprocess.check_output(['git', '-C', str(root), *args])
    return value if binary else value.decode().strip()


def clean_head(root, commit):
    if not isinstance(commit, str) or re.fullmatch('[0-9a-f]{40}', commit) is None or git(root, 'rev-parse', 'HEAD') != commit:
        raise ValueError('Actual full reviewed unified commit required')
    if commit in (HISTORICAL_SCIENCE, HISTORICAL_LAUNCHER):
        raise ValueError('Historical commit cannot authorize a future unified implementation')
    if git(root, 'status', '--porcelain=v1', '-uall'):
        raise ValueError('Clean unified worktree required')
    # Direct blob checks also catch assume-unchanged/skip-worktree modifications.
    entries = git(root, 'ls-tree', '-rz', commit, binary=True).split(b'\0')
    tracked = set()
    for entry in filter(None, entries):
        header, raw = entry.split(b'\t', 1)
        mode, kind, expected = header.decode().split()
        relative = raw.decode(); path = canonical(root / relative)
        if kind != 'blob' or mode not in ('100644', '100755') or not path.is_file():
            raise ValueError('Unsupported unified source entry: ' + relative)
        data = path.read_bytes()
        if hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest() != expected:
            raise ValueError('Unified source blob changed: ' + relative)
        if bool(path.stat().st_mode & 0o111) != (mode == '100755'):
            raise ValueError('Unified source mode changed: ' + relative)
        tracked.add(relative)
    current = {str(p.relative_to(root)) for base in ('reid', 'scripts', 'tests', 'configs')
               for p in (root / base).rglob('*') if p.is_file() and p.suffix in ('.py', '.yaml', '.yml')}
    if not current.issubset(tracked):
        raise ValueError('Untracked/ignored executable source membership changed')
    return git(root, 'rev-parse', commit + '^{tree}')


def private_record(path):
    path = canonical(path)
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o077:
            raise ValueError('Operator audit record must be owned, private and regular (0600)')
        raw = stream.read()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def write_private(path, value):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(encode(value)); stream.flush(); os.fsync(stream.fileno())


def candidate(config, root=ROOT):
    root = canonical(root)
    raw = Path(config); path = canonical(raw if raw.is_absolute() else root / raw)
    relative = str(path.relative_to(root))
    index_bytes = git(root, 'show', HISTORICAL_SCIENCE + ':' + INDEX, binary=True)
    if (root / INDEX).read_bytes() != index_bytes:
        raise ValueError('Historical candidate index changed')
    rows = json.loads(index_bytes)['runs']
    if len(rows) != 8 or len({r['config'] for r in rows}) != 8:
        raise ValueError('Invalid eight-candidate registry')
    matches = [r for r in rows if r['config'] == relative]
    if len(matches) != 1:
        raise ValueError('Config is not one of the eight frozen candidates')
    row = matches[0]; manifest_path = canonical(root / row['manifest'])
    manifest_bytes = git(root, 'show', HISTORICAL_SCIENCE + ':' + row['manifest'], binary=True)
    if manifest_path.read_bytes() != manifest_bytes or path.read_bytes() != git(root, 'show', HISTORICAL_SCIENCE + ':' + relative, binary=True):
        raise ValueError('Historical YAML/manifest changed')
    manifest = json.loads(manifest_bytes)
    if (sha(path) != row['config_file_sha256'] or digest(manifest['immutable']) != manifest['immutable_sha256']
            or manifest['immutable_sha256'] != row['manifest_immutable_sha256']
            or manifest['immutable']['configuration']['path'] != relative):
        raise ValueError('YAML/manifest/index identity mismatch')
    return row, manifest, manifest_path


def binding_path(config, root=ROOT):
    row, _, _ = candidate(config, root)
    return canonical(root / '.local/lodo_operational/v2/bindings' / (Path(row['config']).stem + '.json'))


def make_binding(config, *, root, commit, run_id, policy_path):
    """Prepare an unsigned binding AFTER review/freeze; confers no authority.

    This phase creates no real binding, declaration or future freeze. Historical
    manifests are references, not claims that their old code snapshot matches the
    new executable. The actual unified Git tree is independently verified.
    """
    root = canonical(root); tree = clean_head(root, commit)
    if re.fullmatch(r'unified-[A-Za-z0-9][A-Za-z0-9._-]*', run_id) is None:
        raise ValueError('Future run ID must begin unified-')
    row, manifest, path = candidate(config, root); imm = manifest['immutable']
    policy = canonical(policy_path)
    if sha(policy) != POLICY_SHA:
        raise ValueError('Standing allocation policy SHA256 mismatch')
    run = root / 'exp/lodo/v1' / row['architecture'] / row['fold'] / 'seed42' / run_id
    return dict(schema_version=2, record_type='lodo_unified_operational_binding',
                root=str(root), commit=commit, source_tree=tree,
                historical_scientific_commit=HISTORICAL_SCIENCE, historical_launcher_commit=HISTORICAL_LAUNCHER,
                config=row['config'], config_sha256=sha(root / row['config']),
                manifest=row['manifest'], manifest_sha256=sha(path), immutable_sha256=manifest['immutable_sha256'],
                scientific_sha256=imm['configuration']['scientific_sha256'],
                dataset=copy.deepcopy(imm['dataset']), pretrained=copy.deepcopy(imm['pretrained']),
                execution=copy.deepcopy(imm['execution_candidate']), recovery=copy.deepcopy(imm['recovery']),
                gpu_uuid=GPU, num_workers=0, run_dir=str(run),
                policy=dict(path=str(policy), sha256=POLICY_SHA), interpreter=dict(path=str(PYTHON), sha256=sha(PYTHON)))


def load_binding(config, root=ROOT):
    root = canonical(root); path = binding_path(config, root)
    if not path.is_file():
        raise ValueError('Reviewed unified operational binding v2 is required; no execution approved')
    binding, hash_value = private_record(path)
    run = canonical(binding['run_dir'])
    expected = make_binding(config, root=root, commit=binding['commit'], run_id=run.name, policy_path=binding['policy']['path'])
    if encode(binding) != encode(expected):
        raise ValueError('Operational binding v2 identity mismatch')
    return dict(path=str(path), sha256=hash_value, record=binding)


def configuration(binding, resume_path=None):
    from reid.utils.config import load_config
    from reid.utils.lodo_protocol import configuration_identity
    b = binding['record']; root = Path(b['root'])
    cfg = load_config(str(root / b['config']))
    if (configuration_identity(cfg) != b['scientific_sha256'] or cfg['data']['num_workers'] != 0
            or cfg['system']['device'] != 'cuda' or cfg['repro'].get('cuda_policy') != 'strict_cuda_deterministic_v1'
            or canonical(cfg['data']['root']) != Path(b['dataset']['canonical_root'])):
        raise ValueError('Scientific/runtime/dataset binding mismatch')
    cfg['experiment']['output_dir'] = str(Path(b['run_dir']).relative_to(root))
    cfg['train']['save']['resume'] = str(resume_path) if resume_path else ''
    return cfg


def approval(binding, *, resume=False, evaluation=None, root=ROOT):
    path = canonical(root / '.local/lodo_operational/v2/approval.json')
    if not path.is_file():
        raise ValueError('Scoped local operator execution declaration v2 is required')
    record, hash_value = private_record(path); b = binding['record']
    required = {'schema_version', 'record_type', 'root', 'commit', 'approved_by', 'approval_reference', 'training', 'evaluation'}
    if (set(record) != required or type(record['schema_version']) is not int or record['schema_version'] != 2
            or record['record_type'] != 'local_operator_execution_declaration'
            or record['root'] != b['root'] or record['commit'] != b['commit']
            or record['approved_by'] != pwd.getpwuid(os.getuid()).pw_name
            or not isinstance(record['approval_reference'], str) or not record['approval_reference'].strip()
            or not isinstance(record['training'], dict) or not isinstance(record['evaluation'], dict)):
        raise ValueError('Invalid scoped operator audit declaration')
    # Validate every declared training binding, including other scoped folds.
    for config, scope in record['training'].items():
        scoped = binding if config == b['config'] else load_binding(config, root)
        if (not isinstance(scope, dict) or set(scope) != {'binding_sha256', 'allow_resume'}
                or scope['binding_sha256'] != scoped['sha256'] or type(scope['allow_resume']) is not bool):
            raise ValueError('Invalid training scope binding')
    for relative, scope in record['evaluation'].items():
        path_value = Path(relative)
        if (path_value.is_absolute() or '..' in path_value.parts or not isinstance(scope, dict)
                or set(scope) != {'request_sha256', 'binding_sha256', 'terminal_sha256'}
                or any(not isinstance(v, str) or re.fullmatch('[0-9a-f]{64}', v) is None for v in scope.values())):
            raise ValueError('Invalid evaluation scope binding')
        canonical(root / path_value)
    if evaluation is None:
        scope = record['training'].get(b['config'])
        if (not isinstance(scope, dict) or set(scope) != {'binding_sha256', 'allow_resume'}
                or scope['binding_sha256'] != binding['sha256'] or type(scope['allow_resume']) is not bool
                or (resume and not scope['allow_resume'])):
            raise ValueError('Training/continuation is outside execution approval scope')
    else:
        request_path, terminal_sha = evaluation
        relative = str(canonical(request_path).relative_to(root))
        expected = dict(request_sha256=sha(request_path), binding_sha256=binding['sha256'], terminal_sha256=terminal_sha)
        if record['evaluation'].get(relative) != expected:
            raise ValueError('Held-out evaluation is outside separate execution approval scope')
    return dict(path=str(path), sha256=hash_value, record=record)


def environment(root):
    env = dict(os.environ)
    for key in ('PYTHONHOME', 'PYTHONSTARTUP', 'TORCH_HOME', 'LODO_ADMISSION_RECEIPT', 'LODO_ADMISSION_SHA256'):
        env.pop(key, None)
    env.update(CUDA_VISIBLE_DEVICES=GPU, LODO_AUTHORIZED_GPU_UUID=GPU, CUBLAS_WORKSPACE_CONFIG=':4096:8',
               PYTHONDONTWRITEBYTECODE='1', OMP_NUM_THREADS='1', MKL_NUM_THREADS='1',
               PYTHONPATH=str(root) + os.pathsep + str(root / 'scripts'))
    return env


def validate_training_admission(config, cfg, *, root=ROOT):
    """CLI gate before image/device/output access; an env Boolean never admits."""
    receipt_path = os.environ.get('LODO_ADMISSION_RECEIPT', '')
    if not receipt_path:
        raise ValueError('Stage B requires a scoped operational admission receipt; use lodo_launch.py')
    path = canonical(receipt_path)
    if not path.is_relative_to(root / '.local/lodo_launch/receipts') or path.name != 'execution-admission.json':
        raise ValueError('Unrecognized scoped admission receipt')
    receipt, hash_value = private_record(path)
    if hash_value != os.environ.get('LODO_ADMISSION_SHA256'):
        raise ValueError('Admission receipt SHA256 mismatch')
    binding = load_binding(config, root); b = binding['record']
    resume = cfg['train']['save'].get('resume') or None
    auth = approval(binding, resume=bool(resume), root=root)
    expected_cfg = configuration(binding, resume)
    expected = training_receipt(binding, auth, expected_cfg, root=root)
    if encode(receipt) != encode(expected) or encode(cfg) != encode(expected_cfg):
        raise ValueError('Scoped admission does not match the actual requested run/config/recovery')
    if any(os.environ.get(k) != expected['environment'][k] for k in CONTROLLED):
        raise ValueError('Admission environment mismatch before CUDA initialization')
    from reid.utils.lodo_protocol import validate_output_path
    validate_output_path(cfg, project_root=root)
    return receipt


def process_identity():
    # execve preserves PID/start ticks. A stale receipt cannot admit a new process,
    # including after PID reuse. This is an audit/replay guard, not authentication.
    fields = Path('/proc/self/stat').read_text().rsplit(')', 1)[1].split()
    return dict(pid=os.getpid(), start_ticks=int(fields[19]),
                boot_id=Path('/proc/sys/kernel/random/boot_id').read_text().strip())


def training_receipt(binding, auth, cfg, *, root=ROOT):
    b = binding['record']; resume = cfg['train']['save'].get('resume') or None
    return dict(schema_version=2, status='ADMITTED_TRAINING', process=process_identity(), root=str(root), commit=b['commit'],
                config=b['config'], binding=binding, approval=auth, resolved_config_sha256=digest(cfg),
                run_dir=b['run_dir'], resume=resume, recovery_sha256=sha(resume) if resume else None,
                environment={k:environment(root)[k] for k in CONTROLLED})


def evaluation_admission(request_path, request, *, root=ROOT):
    """Separate CPU-only evaluation authority before terminal/target execution."""
    from reid.utils.lodo_evaluation import validate_request, validate_terminal, evaluation_output
    validate_request(request)
    from reid.utils.config import load_config
    if load_config(str(canonical(request_path))) != request or request.get('num_workers', 0) != 0:
        raise ValueError('Evaluation request bytes or zero-worker binding mismatch')
    relative = f"configs/lodo/v1/{request['architecture']}_{request['fold'].lower()}_seed42.yaml"
    binding = load_binding(relative, root); b = binding['record']
    bound_cfg = configuration(binding)
    if request['target'] != bound_cfg['data']['test']['dataset']['name']:
        raise ValueError('Evaluation excluded target differs from operational binding')
    terminal = canonical(request['checkpoint'])
    if terminal != Path(b['run_dir']) / 'checkpoints/ckpt_terminal.pth' or request['synthetic'] is not False:
        raise ValueError('Evaluation must reference the bound future same-run terminal')
    expected = dict(config_digest=b['scientific_sha256'], map_digest=b['dataset']['map_digest'],
                    data_digest=b['dataset']['data_digest'], num_classes=b['dataset']['num_classes'])
    if request['expected'] != expected or canonical(request.get('data_root', b['dataset']['canonical_root'])) != Path(b['dataset']['canonical_root']):
        raise ValueError('Evaluation scientific/data identity mismatch')
    auth = approval(binding, evaluation=(request_path, sha(terminal)), root=root)
    payload, proof, _ = validate_terminal(request)
    if payload['cfg']['experiment']['output_dir'] != str(Path(b['run_dir']).relative_to(root)):
        raise ValueError('Terminal run binding mismatch')
    output = evaluation_output(request, project_root=root)
    from reid.utils.lodo_evaluation_device import preflight, execution_spec
    preflight(request, payload['cfg'], output)
    status = 'ADMITTED_CUDA_EVALUATION' if execution_spec(request)['device'] == 'cuda' else 'ADMITTED_CPU_EVALUATION'
    return dict(schema_version=2, status=status, binding=binding, approval=auth,
                request=str(canonical(request_path)), request_sha256=sha(request_path),
                terminal_sha256=proof['checkpoint_sha256'], output_dir=str(output))
